#include<iostream>
using namespace std;

int main(){
	// Comparison operator || give ans in 1 or 0
	
	int a,b;
	cout<<"Enter the value of a :";
	cin>>a;
	cout<<"Enter the value of b :";
	cin>>b;
	
	// ==
	
	if (a==b){
		cout<<"Yes";
	}
	else{
		cout<<"No";
	}
	
	// >
	
	if (a>b){
		cout<<"Yes";
	}
	else{
		cout<<"No";
	}
	
	
	// <
	
	if (a<b){
		cout<<"Yes";
	}
	else{
		cout<<"No";
	}
	
	// >=
	
	if (a>=b){
		cout<<"Yes";
	}
	else{
		cout<<"No";
	}
	
	// <=
	
	if (a<=b){
		cout<<"Yes";
	}
	else{
		cout<<"No";
	}
	
	// !=
	
	if (a!=b){
		cout<<"Yes";
	}
	else{
		cout<<"No";
	}



}
